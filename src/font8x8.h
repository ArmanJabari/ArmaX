static inline const unsigned char* Glyph(char c) {
    int u = (unsigned char)c;
    if (u >= 0x20 && u <= 0x60) return GLYPHS[u - 0x20];
    if (u >= 0x7B && u <= 0x7E) return GLYPHS[65 + (u - 0x7B)];
    return GLYPHS[0];
}

static inline ImVec2 TextSize(const char* text, float scale) {
    int n = 0;
    while (text[n]) n++;
    return ImVec2(n * 8.0f * scale, 8.0f * scale);
}

static inline void Draw(ImDrawList* dl, ImVec2 pos, const char* text, float scale, ImU32 col) {
    for (int i = 0; text[i]; i++) {
        const unsigned char* g = Glyph(text[i]);
        float cx = pos.x + i * 8.0f * scale;
        for (int y = 0; y < 8; y++) {
            for (int x = 0; x < 8; x++) {
                if (g[y] & (0x80 >> x)) {
                    ImVec2 p0(floorf(cx + x * scale), floorf(pos.y + y * scale));
                    ImVec2 p1(floorf(cx + (x + 1) * scale), floorf(pos.y + (y + 1) * scale));
                    dl->AddRectFilled(p0, p1, col);
                }
            }
        }
    }
}

